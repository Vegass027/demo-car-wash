-- ============================================================
-- RLS Политики для public роли
-- ============================================================
-- Этот скрипт создает политики, которые позволяют public роли
-- (используемой через anon ключ) выполнять все операции
-- с таблицами базы данных.
--
-- ВАЖНО: Это открывает доступ к данным для всех пользователей
-- с anon ключом. Безопасность обеспечивается на уровне приложения.
-- ============================================================

DO $$
DECLARE
  t text;
BEGIN
  -- Проходим по всем таблицам в схеме public
  FOR t IN 
    SELECT tablename FROM pg_tables 
    WHERE schemaname = 'public' 
    AND tablename NOT IN (
      'schema_migrations',
      'spatial_ref_sys'
    )
  LOOP
    -- Удаляем существующие политики public_all_access если есть
    EXECUTE format('DROP POLICY IF EXISTS "public_all_access" ON %I', t);
    
    -- Создаем политику для всех операций (SELECT, INSERT, UPDATE, DELETE)
    EXECUTE format('
      CREATE POLICY "public_all_access" 
      ON %I 
      FOR ALL 
      TO public 
      USING (true) 
      WITH CHECK (true)
    ', t);
    
    RAISE NOTICE 'Created policy public_all_access for table: %', t;
  END LOOP;
END $$;

-- ============================================================
-- Проверка: Включен ли RLS на таблицах
-- ============================================================
-- После выполнения этого скрипта, RLS должен быть включен
-- на всех таблицах. Проверьте с помощью:
--
-- SELECT tablename, rowsecurity 
-- FROM pg_tables 
-- WHERE schemaname = 'public';
--
-- rowsecurity = true означает, что RLS включен
