-- ============================================
-- ИСПРАВЛЕНИЕ RLS ПОЛИТИК ДЛЯ ТАБЛИЦЫ services
-- Дата: 2026-02-15
-- Описание: Добавление политики для роли anon, чтобы клиенты могли читать услуги
-- ============================================

-- Проблема:
-- При использовании кастомной аутентификации через Telegram,
-- клиенты используют anon ключ для запросов к БД.
-- Политика "clients_view_active_services" проверяет auth.uid(),
-- который возвращает NULL для anon пользователей, блокируя доступ.

-- Решение:
-- Добавляем политику для роли anon, которая разрешает чтение активных услуг.

-- ============================================
-- ДОБАВЛЯЕМ ПОЛИТИКУ ДЛЯ ANON
-- ============================================

-- Удаляем старую политику для anon (если существует)
DROP POLICY IF EXISTS "Public can view active services" ON services;

-- Создаем новую политику для anon: чтение активных услуг
CREATE POLICY "anon_can_view_active_services"
ON services FOR SELECT
TO anon
USING (is_active = true);

-- Удаляем политику, запрещающую модификацию для anon (если существует)
DROP POLICY IF EXISTS "Public cannot modify services" ON services;

-- Создаем политику, запрещающую модификацию для anon
CREATE POLICY "anon_cannot_modify_services"
ON services FOR ALL
TO anon
USING (false)
WITH CHECK (false);

-- ============================================
-- ПРОВЕРКА
-- ============================================

-- Проверяем, что политики созданы правильно
SELECT 
  policyname,
  cmd,
  roles,
  qual,
  with_check
FROM pg_policies 
WHERE schemaname = 'public'
  AND tablename = 'services'
ORDER BY policyname;

-- ============================================
-- ПРИМЕЧАНИЕ
-- ============================================
-- После этой миграции клиенты смогут:
-- 1. Читать активные услуги (через anon ключ)
-- 2. Не смогут модифицировать услуги (блокируется политикой)
--
-- Админы и владельцы по-прежнему имеют полный доступ
-- через политику "admins_full_access_services" (для authenticated)
